class SbomVerificationResponse(_PhantomBaseModel):
    """Response body for ``GET /api/v1/sboms/{sbom_id}/verification``.

    Attributes:
        verification_job_id: UUID identifying this verification job.
        sbom_id: UUID of the SBOM being verified.
        status: Current or final job status.
        signing_identity: Verified Fulcio identity; None if not yet verified.
        issuer: Verified OIDC issuer; None if not yet verified.
        rekor_entry_uuid: Rekor transparency log entry UUID; None if not recorded.
        verified_at: UTC timestamp of successful verification; None if pending/failed.
        failure_reason: Human-readable failure description; None if not failed.
    """

    verification_job_id: uuid.UUID
    sbom_id: uuid.UUID
    status: Literal["queued", "running", "verified", "failed"]
    signing_identity: str | None = None
    issuer: str | None = None
    rekor_entry_uuid: uuid.UUID | None = None
    verified_at: datetime | None = None
    failure_reason: str | None = None
