"""
phantom_core.models.sbom — Pydantic models for SBOM API contracts (B.2).

Covers:
- SbomIngestRequest: POST /api/v1/sboms
- SbomRecord: response record embedded in ingest and detail responses
- SbomDetailResponse: GET /api/v1/sboms/{sbom_id}
- SbomVerificationRequest: POST /api/v1/sboms/{sbom_id}/verification
- VerificationJobResponse: response to POST verification
- SbomVerificationResponse: GET /api/v1/sboms/{sbom_id}/verification
"""

from __future__ import annotations

import re
import uuid
from datetime import datetime
from typing import Any, Literal

from pydantic import AnyUrl, Field, field_validator, model_validator

from phantom_core.constants import (
    DIGEST_PATTERN,
    SBOM_ARTIFACT_URI_SCHEMES,
    SCHEMA_VERSION,
)
from phantom_core.models.common import _PhantomBaseModel


def _validate_digest(value: str) -> str:
    """Validate that a string matches the sha256:<64 hex chars> digest format.

    Args:
        value: The digest string to validate.

    Returns:
        The validated digest string, unchanged.

    Raises:
        ValueError: If the value does not match the digest pattern.
    """
    if not re.fullmatch(DIGEST_PATTERN, value):
        raise ValueError(
            f"Digest must match {DIGEST_PATTERN!r}, got {value!r}"
        )
    return value


def _validate_uri_scheme(value: AnyUrl) -> AnyUrl:
    """Validate that a URI uses only https or s3 scheme.

    Args:
        value: The AnyUrl value to validate.

    Returns:
        The validated AnyUrl, unchanged.

    Raises:
        ValueError: If the scheme is not https or s3.
    """
    scheme = str(value).split("://")[0].lower() if "://" in str(value) else ""
    if scheme not in SBOM_ARTIFACT_URI_SCHEMES:
        raise ValueError(
            f"URI scheme must be one of {SBOM_ARTIFACT_URI_SCHEMES}, got {scheme!r}"
        )
    return value


