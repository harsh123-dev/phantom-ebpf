class SbomIngestRequest(_PhantomBaseModel):
    """Request body for ``POST /api/v1/sboms``.

    Attributes:
        schema_version: Always ``"v1"``.
        image_digest: sha256 digest of the associated container image.
        artifact_uri: https or s3 URI pointing to the SBOM artifact.
        cyclonedx_document: Non-empty CycloneDX JSON document.
        declared_sbom_digest: sha256 digest of the CycloneDX document.
        source: Whether the SBOM was generated by Syft or submitted externally.
        generated_at: UTC timestamp when the SBOM was generated.
        signature_bundle_uri: Required when ``source="external"``; https or s3 only.
        tenant_id: Logical isolation key for multi-namespace evaluation.
    """

    schema_version: Literal["v1"] = SCHEMA_VERSION  # type: ignore[assignment]
    image_digest: str
    artifact_uri: AnyUrl
    cyclonedx_document: dict[str, Any] = Field(..., min_length=1)
    declared_sbom_digest: str
    source: Literal["syft", "external"]
    generated_at: datetime
    signature_bundle_uri: AnyUrl | None = None
    tenant_id: uuid.UUID

    @field_validator("image_digest", "declared_sbom_digest", mode="after")
    @classmethod
    def _check_digest(cls, v: str) -> str:
        """Validate digest fields match sha256:<64 hex> format.

        Args:
            v: The digest string.

        Returns:
            The validated digest string.
        """
        return _validate_digest(v)

    @field_validator("artifact_uri", "signature_bundle_uri", mode="after")
    @classmethod
    def _check_uri_scheme(cls, v: AnyUrl | None) -> AnyUrl | None:
        """Validate URI scheme is https or s3.

        Args:
            v: The URI value.

        Returns:
            The validated URI.
        """
        if v is None:
            return v
        return _validate_uri_scheme(v)

    @model_validator(mode="after")
    def _require_signature_for_external(self) -> SbomIngestRequest:
        """Require signature_bundle_uri when source is external.

        Returns:
            The validated model instance.

        Raises:
            ValueError: If source is external but signature_bundle_uri is absent.
        """
        if self.source == "external" and self.signature_bundle_uri is None:
            raise ValueError(
                "signature_bundle_uri is required when source='external'"
            )
        return self


class SbomRecord(_PhantomBaseModel):
    """SBOM record returned from ingest and embedded in detail responses.

    Attributes:
        sbom_id: Immutable UUID assigned at ingest time.
        image_digest: sha256 digest of the associated container image.
        sbom_digest: sha256 digest of the CycloneDX document as stored.
        format: Always ``"CycloneDX"``.
        spec_version: CycloneDX specification version string (e.g. ``"1.5"``).
        component_count: Number of components in the SBOM; non-negative.
        verification_status: Current cosign verification state.
        created_at: UTC timestamp when this record was created.
    """

    sbom_id: uuid.UUID
    image_digest: str
    sbom_digest: str
    format: Literal["CycloneDX"]
    spec_version: str = Field(..., min_length=1)
    component_count: int = Field(..., ge=0)
    verification_status: Literal["pending", "verified", "failed"]
    created_at: datetime


class SbomDetailResponse(_PhantomBaseModel):
    """Response body for ``GET /api/v1/sboms/{sbom_id}``.

    Attributes:
        record: Embedded SbomRecord.
        cyclonedx_document: The full CycloneDX JSON document as stored.
        purl_count: Number of PURLs resolved from this SBOM; non-negative.
        signature_bundle_uri: URI of the cosign signature bundle if present.
        verified_at: UTC timestamp when verification completed; None if pending.
        verification_error: Error message if verification failed; None otherwise.
    """

    record: SbomRecord
    cyclonedx_document: dict[str, Any]
    purl_count: int = Field(..., ge=0)
    signature_bundle_uri: str | None = None
    verified_at: datetime | None = None
    verification_error: str | None = None


