class SbomVerificationRequest(_PhantomBaseModel):
    """Request body for ``POST /api/v1/sboms/{sbom_id}/verification``.

    Attributes:
        expected_identity: Expected Fulcio/Sigstore signing identity; 1..512 chars.
        expected_issuer: Expected OIDC issuer URI.
        rekor_required: Whether a Rekor transparency log entry is mandatory.
    """

    expected_identity: str = Field(..., min_length=1, max_length=512)
    expected_issuer: AnyUrl
    rekor_required: bool = True


class VerificationJobResponse(_PhantomBaseModel):
    """Response body for ``POST /api/v1/sboms/{sbom_id}/verification``.

    Attributes:
        verification_job_id: UUID identifying this verification job.
        sbom_id: UUID of the SBOM being verified.
        status: Current job status.
        submitted_at: UTC timestamp when the job was enqueued.
    """

    verification_job_id: uuid.UUID
    sbom_id: uuid.UUID
    status: Literal["queued", "running", "verified", "failed"]
    submitted_at: datetime


