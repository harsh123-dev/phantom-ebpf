@dataclass(frozen=True)
class ImageDigest:
    """Immutable value object wrapping a validated container image digest.

    Attributes:
        value: The raw digest string, e.g. ``sha256:<64 hex chars>``.
    """

    value: str
    """Raw digest string in sha256:<64 hex chars> format."""

    def __post_init__(self) -> None:
        """Validate the digest format on construction.

        Raises:
            ValueError: If the digest does not match the required format.
        """
        if not _DIGEST_RE.match(self.value):
            raise ValueError(
                f"ImageDigest must match sha256:<64 hex chars>, got {self.value!r}"
            )

    def __str__(self) -> str:
        """Return the raw digest string.

        Returns:
            The raw digest string.
        """
        return self.value


@dataclass(frozen=True)
class SbomDigest:
    """Immutable value object wrapping a validated SBOM document digest.

    Attributes:
        value: The raw digest string, e.g. ``sha256:<64 hex chars>``.
    """

    value: str
    """Raw digest string in sha256:<64 hex chars> format."""

    def __post_init__(self) -> None:
        """Validate the digest format on construction.

        Raises:
            ValueError: If the digest does not match the required format.
        """
        if not _DIGEST_RE.match(self.value):
            raise ValueError(
                f"SbomDigest must match sha256:<64 hex chars>, got {self.value!r}"
            )

    def __str__(self) -> str:
        """Return the raw digest string.

        Returns:
            The raw digest string.
        """
        return self.value

    @classmethod
    def compute(cls, cyclonedx_document: dict[str, Any]) -> SbomDigest:
        """Compute the canonical sha256 digest of a CycloneDX document.

        Uses JSON with sorted keys and no extra whitespace to ensure
        deterministic digests regardless of input serialization order.

        Args:
            cyclonedx_document: The CycloneDX document as a parsed dict.

        Returns:
            The SbomDigest of the canonicalized document.
        """
        canonical_bytes = json.dumps(
            cyclonedx_document, sort_keys=True, separators=(",", ":")
        ).encode("utf-8")
        hex_digest = hashlib.sha256(canonical_bytes).hexdigest()
        return cls(value=f"sha256:{hex_digest}")


@dataclass(frozen=True)
class Purl:
    """Immutable value object for a Package URL (PURL).

    Attributes:
        value: The raw PURL string; 1..2048 characters.
    """

    value: str
    """Raw PURL string; 1..2048 characters."""

    def __post_init__(self) -> None:
        """Validate basic PURL constraints.

        Raises:
            ValueError: If the PURL is empty or exceeds 2048 characters.
        """
        if not self.value:
            raise ValueError("Purl value must not be empty")
        if len(self.value) > 2048:
            raise ValueError(
                f"Purl value must be at most 2048 characters, got {len(self.value)}"
            )

    def __str__(self) -> str:
        """Return the raw PURL string.

        Returns:
            The raw PURL string.
        """
        return self.value


