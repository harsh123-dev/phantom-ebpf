"""
services/sbom-service/app/domain/entities.py

Pure domain entities for the SBOM service.

Rules enforced here:
- NO imports from infrastructure/, application/, or interface/.
- NO framework imports (no FastAPI, SQLAlchemy, asyncpg, etc.).
- All fields are typed; optional fields have a default.
- Frozen dataclasses guarantee value-object immutability.
- Business invariants are enforced in __post_init__ or classmethods.
"""

from __future__ import annotations

import hashlib
import json
import re
import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from enum import Enum
from typing import Any

# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class VerificationStatus(str, Enum):
    """Cosign/Sigstore signature verification lifecycle state."""

    PENDING = "pending"
    """Verification has not yet started or is enqueued."""

    VERIFIED = "verified"
    """Verification completed successfully; signature is trusted."""

    FAILED = "failed"
    """Verification completed but the signature is invalid or absent."""


class SbomSource(str, Enum):
    """Provenance of the submitted SBOM document."""

    SYFT = "syft"
    """Generated by the Syft CLI during CI or admission control."""

    EXTERNAL = "external"
    """Submitted by an external producer; signature bundle is mandatory."""


class BindingStatus(str, Enum):
    """Quality of a PURL-to-runtime component binding."""

    RESOLVED = "resolved"
    """PURL is unambiguously matched to a runtime component."""

    AMBIGUOUS = "ambiguous"
    """Multiple PURLs match; binding is uncertain."""

    MISSING = "missing"
    """No SBOM binding could be established for this component."""


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_DIGEST_RE = re.compile(r"^sha256:[0-9a-f]{64}$")
"""Pattern for validating sha256:<64 hex chars> digest fields."""

_CYCLONEDX_FORMAT_FIELD = "bomFormat"
"""Required top-level field in a CycloneDX JSON document."""

_CYCLONEDX_COMPONENTS_FIELD = "components"
"""Field name for the component list in a CycloneDX document."""


